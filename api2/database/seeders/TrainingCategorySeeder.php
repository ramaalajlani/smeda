    public function run(): void
    {
        if (TrainingCategory::query()->exists()) {
            return;
        }

        $tree = $this->categoryTree();
        $order = 0;

        foreach ($tree as $rootName => $children) {
            $order++;
            $root = TrainingCategory::create([
                'parent_id' => null,
                'name_ar' => $rootName,
                'name_en' => $this->rootEnglish($rootName),
                'slug' => $this->uniqueSlug($rootName),
                'sort_order' => $order,
                'is_active' => true,
            ]);

            $childOrder = 0;
            foreach ($children as $childName) {
                $childOrder++;
                TrainingCategory::create([
                    'parent_id' => $root->id,
                    'name_ar' => $childName,
                    'name_en' => null,
                    'slug' => $this->uniqueSlug($root->slug . '-' . $childName),
                    'sort_order' => $childOrder,
                    'is_active' => true,
                ]);
            }
        }
    }

    private function uniqueSlug(string $label): string
    {
        $base = Str::slug($label, '-', 'ar');
        if ($base === '') {
            $base = 'cat-' . substr(md5($label), 0, 8);
        }

        $slug = $base;
        $i = 1;
        while (TrainingCategory::withTrashed()->where('slug', $slug)->exists()) {
            $slug = $base . '-' . $i;
            $i++;
        }

        return $slug;
    }

